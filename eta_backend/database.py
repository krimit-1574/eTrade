DB_PATH = os.getenv(
    "ETA_DB_PATH",
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "eta.db"),
)

DEFAULT_VIRTUAL_CASH = 1_000_000.0
DEFAULT_AUTH_TTL_SECONDS = 7 * 24 * 60 * 60


def _connect():
    """Open a consistently configured SQLite connection."""
    conn = sqlite3.connect(DB_PATH, timeout=10)
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA busy_timeout = 10000")
    return conn


def _canonical_symbol(symbol):
    if not isinstance(symbol, str):
        raise ValueError("Symbol must be a string.")
    value = symbol.strip().upper()
    if not value or len(value) > 64 or any(ord(ch) < 32 for ch in value):
        raise ValueError("Invalid symbol.")
    return value


def _finite_positive(value, label):
    try:
        number = float(value)
    except (TypeError, ValueError, OverflowError):
        raise ValueError(f"{label} must be a number.")
    if not math.isfinite(number) or number <= 0:
        raise ValueError(f"{label} must be a finite number greater than zero.")
    return number

def is_guest(user_id):
    return str(user_id).strip().lower() == 'guest'

def normalize_user_id(user_id):
    return str(user_id).strip()


def user_exists(user_id):
    if is_guest(user_id) or user_id is None:
        return False
    conn = _connect()
    try:
        row = conn.execute("SELECT 1 FROM users WHERE id = ?", (user_id,)).fetchone()
        return row is not None
    finally:
        conn.close()

def init_db():
    conn = _connect()
    try:
        conn.execute("BEGIN IMMEDIATE")
        _initialize_schema(conn)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _initialize_schema(conn):
    c = conn.cursor()
    c.execute('''CREATE TABLE IF NOT EXISTS users
                 (id INTEGER PRIMARY KEY, username TEXT UNIQUE, password TEXT, settings TEXT)''')
    
    # Add legacy columns explicitly. Avoid swallowing unrelated OperationalError
    # exceptions such as a locked/corrupt database or failed migration.
    user_columns = {row[1] for row in c.execute("PRAGMA table_info(users)").fetchall()}
    if "email" not in user_columns:
        c.execute("ALTER TABLE users ADD COLUMN email TEXT")
    if "dob" not in user_columns:
        c.execute("ALTER TABLE users ADD COLUMN dob TEXT")
    if "virtual_cash" not in user_columns:
        c.execute("ALTER TABLE users ADD COLUMN virtual_cash REAL DEFAULT 1000000.0")

    c.execute('''CREATE TABLE IF NOT EXISTS portfolio
                 (id INTEGER PRIMARY KEY, user_id TEXT, name TEXT, symbol TEXT, quantity REAL, buy_price REAL)''')
    c.execute('''CREATE TABLE IF NOT EXISTS watchlist
                 (id INTEGER PRIMARY KEY, user_id TEXT, name TEXT, symbol TEXT, alert_price REAL, alert_dir TEXT)''')
    c.execute('''CREATE TABLE IF NOT EXISTS transactions
                 (id INTEGER PRIMARY KEY, user_id TEXT, symbol TEXT, name TEXT, order_type TEXT, quantity REAL, price REAL, total_amount REAL, timestamp TEXT)''')
    c.execute('''CREATE TABLE IF NOT EXISTS ai_sessions
                 (id TEXT NOT NULL, user_id TEXT NOT NULL, symbol TEXT, start_time TEXT, end_time TEXT,
                  starting_capital REAL, ending_capital REAL, status TEXT, realized_pnl REAL,
                  trade_count INTEGER, analytics_json TEXT, trades_json TEXT, decisions_json TEXT,
                  timeline_json TEXT, created_at TEXT,
                  PRIMARY KEY(user_id, id))''')
    c.execute('''CREATE TABLE IF NOT EXISTS paper_positions
                 (id INTEGER PRIMARY KEY, user_id TEXT NOT NULL, name TEXT NOT NULL,
                  symbol TEXT NOT NULL, quantity REAL NOT NULL, buy_price REAL NOT NULL,
                  UNIQUE(user_id, symbol))''')
    c.execute('''CREATE TABLE IF NOT EXISTS auth_sessions
                 (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL, created_at INTEGER NOT NULL,
                  expires_at INTEGER NOT NULL, revoked_at INTEGER,
                  FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE)''')
    c.execute('''CREATE TABLE IF NOT EXISTS schema_migrations
                 (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL)''')

    # Session ids are generated by clients and can legitimately collide across
    # users. Upgrade the old global-id primary key without changing external ids.
    ai_session_pk = [
        row[1]
        for row in sorted(c.execute("PRAGMA table_info(ai_sessions)").fetchall(), key=lambda row: row[5])
        if row[5]
    ]
    if ai_session_pk == ["id"]:
        source_count = c.execute("SELECT COUNT(*) FROM ai_sessions").fetchone()[0]
        c.execute('''CREATE TABLE ai_sessions_user_scoped
                     (id TEXT NOT NULL, user_id TEXT NOT NULL, symbol TEXT, start_time TEXT, end_time TEXT,
                      starting_capital REAL, ending_capital REAL, status TEXT, realized_pnl REAL,
                      trade_count INTEGER, analytics_json TEXT, trades_json TEXT, decisions_json TEXT,
                      timeline_json TEXT, created_at TEXT, PRIMARY KEY(user_id, id))''')
        c.execute('''INSERT INTO ai_sessions_user_scoped
                     (id, user_id, symbol, start_time, end_time, starting_capital, ending_capital,
                      status, realized_pnl, trade_count, analytics_json, trades_json, decisions_json,
                      timeline_json, created_at)
                     SELECT id, user_id, symbol, start_time, end_time, starting_capital, ending_capital,
                            status, realized_pnl, trade_count, analytics_json, trades_json, decisions_json,
                            '[]', created_at
                     FROM ai_sessions''')
        migrated_count = c.execute("SELECT COUNT(*) FROM ai_sessions_user_scoped").fetchone()[0]
        if migrated_count != source_count:
            raise RuntimeError("AI session migration did not preserve every row.")
        c.execute("DROP TABLE ai_sessions")
        c.execute("ALTER TABLE ai_sessions_user_scoped RENAME TO ai_sessions")

    ai_session_columns = {row[1] for row in c.execute("PRAGMA table_info(ai_sessions)").fetchall()}
    if "timeline_json" not in ai_session_columns:
        c.execute("ALTER TABLE ai_sessions ADD COLUMN timeline_json TEXT DEFAULT '[]'")

    c.execute("CREATE INDEX IF NOT EXISTS idx_portfolio_user ON portfolio(user_id)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_watchlist_user ON watchlist(user_id)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_transactions_user ON transactions(user_id, id DESC)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_ai_sessions_user ON ai_sessions(user_id, created_at DESC)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_auth_sessions_user ON auth_sessions(user_id)")
    # Older versions allowed duplicate watchlist rows. Keep the most recent row and
    # enforce the invariant used by toggle/check operations.
    c.execute(
        "DELETE FROM watchlist WHERE id NOT IN ("
        "SELECT MAX(id) FROM watchlist GROUP BY user_id, lower(symbol))"
    )
    c.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_watchlist_user_symbol "
        "ON watchlist(user_id, symbol COLLATE NOCASE)"
    )

    # Migrate positions produced by older releases, where paper positions and
    # manually entered portfolio holdings shared one table. Replaying the paper
    # transaction ledger avoids importing free-form holdings into paper cash.
    paper_migration = "paper_positions_from_transactions_v1"
    if c.execute("SELECT 1 FROM schema_migrations WHERE name = ?", (paper_migration,)).fetchone() is None:
        reconstructed = {}
        rows = c.execute(
            "SELECT user_id, symbol, name, order_type, quantity, price "
            "FROM transactions ORDER BY id"
        ).fetchall()
        for uid, raw_symbol, name, side, raw_qty, raw_price in rows:
            try:
                symbol = _canonical_symbol(raw_symbol)
                qty = _finite_positive(raw_qty, "Quantity")
                price = _finite_positive(raw_price, "Price")
            except ValueError:
                continue
            key = (normalize_user_id(uid), symbol)
            current_qty, current_avg, current_name = reconstructed.get(key, (0.0, 0.0, name or symbol))
            if str(side).upper() == "BUY":
                new_qty = current_qty + qty
                new_avg = ((current_qty * current_avg) + (qty * price)) / new_qty
                reconstructed[key] = (new_qty, new_avg, name or current_name or symbol)
            elif str(side).upper() == "SELL" and current_qty + 1e-9 >= qty:
                new_qty = max(0.0, current_qty - qty)
                reconstructed[key] = (new_qty, current_avg, current_name)
        for (uid, symbol), (qty, avg_price, name) in reconstructed.items():
            if qty > 1e-9:
                c.execute(
                    "INSERT OR IGNORE INTO paper_positions "
                    "(user_id, name, symbol, quantity, buy_price) VALUES (?, ?, ?, ?, ?)",
                    (uid, name or symbol, symbol, qty, avg_price),
                )
        c.execute(
            "INSERT INTO schema_migrations (name, applied_at) VALUES (?, ?)",
            (paper_migration, datetime.now(timezone.utc).isoformat()),
        )

    # Remove only exact legacy mirrors left by the old implementation that
    # wrote paper trades into the manual portfolio table. Run once so future
    # intentionally matching manual holdings are preserved.
    split_migration = "paper_portfolio_split_v2"
    if c.execute("SELECT 1 FROM schema_migrations WHERE name = ?", (split_migration,)).fetchone() is None:
        # Exact matches are the best available signal in databases created by
        # the legacy implementation, but a user could also have entered the
        # same holding manually. Preserve every candidate row for recovery.
        c.execute('''CREATE TABLE IF NOT EXISTS portfolio_migration_backup
                     (migration TEXT NOT NULL, original_id INTEGER NOT NULL,
                      user_id TEXT, name TEXT, symbol TEXT, quantity REAL, buy_price REAL,
                      backed_up_at TEXT NOT NULL, PRIMARY KEY(migration, original_id))''')
        backed_up_at = datetime.now(timezone.utc).isoformat()
        c.execute(
            "INSERT OR IGNORE INTO portfolio_migration_backup "
            "(migration, original_id, user_id, name, symbol, quantity, buy_price, backed_up_at) "
            "SELECT ?, portfolio.id, portfolio.user_id, portfolio.name, portfolio.symbol, "
            "portfolio.quantity, portfolio.buy_price, ? FROM portfolio WHERE EXISTS ("
            "SELECT 1 FROM paper_positions p "
            "WHERE p.user_id = portfolio.user_id "
            "AND p.symbol = portfolio.symbol COLLATE NOCASE "
            "AND abs(p.quantity - portfolio.quantity) < 0.000000001 "
            "AND abs(p.buy_price - portfolio.buy_price) < 0.0001)",
            (split_migration, backed_up_at),
        )
        c.execute(
            "DELETE FROM portfolio WHERE id IN ("
            "SELECT original_id FROM portfolio_migration_backup WHERE migration = ?) ",
            (split_migration,),
        )
        c.execute(
            "INSERT INTO schema_migrations (name, applied_at) VALUES (?, ?)",
            (split_migration, datetime.now(timezone.utc).isoformat()),
        )

def hash_password(password):
    salt = os.urandom(16)
    pw_hash = hashlib.pbkdf2_hmac('sha256', password.encode('utf-8'), salt, 100000)
    return binascii.hexlify(salt + pw_hash).decode('ascii')

def check_password(password, hashed_password):
    if not hashed_password:
        return False
    # If it's an old plain-text password from earlier dev work
    if len(hashed_password) < 60:
        return hmac.compare_digest(password, hashed_password)
    try:
        data = binascii.unhexlify(hashed_password)
        if len(data) != 48:
            return False
        salt = data[:16]
        stored_hash = data[16:]
        pw_hash = hashlib.pbkdf2_hmac('sha256', password.encode('utf-8'), salt, 100000)
        return hmac.compare_digest(pw_hash, stored_hash)
    except (TypeError, ValueError, binascii.Error):
        return False

def create_user(username, password, email="", dob=""):
    username = str(username).strip()
    email = str(email).strip().lower()
    conn = _connect()
    c = conn.cursor()
    try:
        c.execute("BEGIN IMMEDIATE")
        # Username and email share the login identifier namespace. Prevent an
        # account from shadowing another account's username/email login.
        username_key = username.lower()
        c.execute(
            "SELECT id FROM users WHERE lower(username) = ? "
            "OR (email IS NOT NULL AND email <> '' AND lower(email) = ?) "
            "OR (? <> '' AND (lower(username) = ? OR lower(email) = ?)) "
            "LIMIT 1",
            (username_key, username_key, email, email, email),
        )
        if c.fetchone():
            conn.rollback()
            return None
        c.execute("INSERT INTO users (username, password, settings, email, dob) VALUES (?, ?, ?, ?, ?)", 
                  (username, hash_password(password), json.dumps({'av_key': '', 'gemini_key': ''}), email, dob))
        conn.commit()
        return c.lastrowid
    except sqlite3.IntegrityError:
        conn.rollback()
        return None
    finally:
        conn.close()

def verify_user(username, password):
    identifier = str(username).strip()
    conn = _connect()
    c = conn.cursor()
    # Allow logging in by either username or email
    c.execute(
        "SELECT id, password FROM users "
        "WHERE username = ? OR lower(email) = lower(?) ORDER BY username = ? DESC LIMIT 1",
        (identifier, identifier, identifier),
    )
    user = c.fetchone()
    if not user or not check_password(password, user[1]):
        conn.close()
        return None

    # Upgrade legacy plaintext development passwords on successful login.
    if len(user[1]) < 60:
        c.execute("UPDATE users SET password = ? WHERE id = ?", (hash_password(password), user[0]))
        conn.commit()
    conn.close()
    return user[0]


